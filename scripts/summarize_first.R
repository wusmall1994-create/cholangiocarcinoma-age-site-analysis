library(data.table)
args <- commandArgs(trailingOnly=TRUE)
out <- args[1]
files <- list.files(out,pattern='^rep_[0-9]{4}[.]rds$',full.names=TRUE)
stopifnot(length(files)==2000L, identical(sort(basename(files)),sprintf('rep_%04d.rds',1:2000)))
replicates <- lapply(files,readRDS)
warning_counts <- lengths(lapply(replicates,'[[','warnings'))
stopifnot(!any(warning_counts))
z <- rbindlist(lapply(replicates,'[[','value'),idcol='replicate')
keys <- c('definition','contrast')
stopifnot(nrow(z)==18000L, !anyDuplicated(z[,c('replicate',keys),with=FALSE]))
w <- dcast(z,replicate+contrast~definition,value.var='estimate')
stopifnot(max(abs(w$Common_biliary-w$SEER_original-w$Common_biliary_minus_SEER))<1e-12)
w <- dcast(z,replicate+definition~contrast,value.var='estimate')
stopifnot(max(abs(w$RD_age75-w$RD_age50-w$RD_change_75_minus_50))<1e-12)
ci <- z[,.(lower95=quantile(estimate,.025,type=7),upper95=quantile(estimate,.975,type=7),replicates=.N), by=keys]
point <- fread(file.path(out,'point.csv'))
summary <- merge(point,ci,by=keys)
stopifnot(nrow(summary)==9L,all(summary$replicates==2000L))
fwrite(summary,file.path(out,'summary.csv'))
print(summary)
