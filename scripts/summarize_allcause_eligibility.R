options(stringsAsFactors=FALSE)
suppressPackageStartupMessages(library(data.table))
out<-Sys.getenv('CCA_ALLCAUSE_RESULTS_DIR');stopifnot(nzchar(out))
point<-fread(file.path(out,'allcause_point_contrasts.csv'))
files<-list.files(file.path(out,'bootstrap'),'^rep_[0-9]{4}[.]rds$',full.names=TRUE)
stopifnot(length(files)==1000L)
reps<-lapply(files,readRDS)
stopifnot(identical(sort(vapply(reps,`[[`,integer(1),'replicate')),1:1000))
stopifnot(all(vapply(reps,function(x)!is.null(x$value),logical(1))))
all<-rbindlist(lapply(reps,function(x){z<-copy(x$value$contrasts);z[,replicate:=x$replicate];z}))
stopifnot(nrow(all)==1000L*nrow(point),!anyNA(all$estimate),all(is.finite(all$estimate)))
ci<-all[,.(lower95=quantile(estimate,.025,type=7),upper95=quantile(estimate,.975,type=7),replicates=.N,bootstrap_mean=mean(estimate)),by=.(specification,contrast)]
stopifnot(all(ci$replicates==1000L))
ci<-merge(point,ci,by=c('specification','contrast'),sort=FALSE)
fwrite(ci,file.path(out,'allcause_contrasts_with_CI.csv'))
key<-ci[contrast%chin%c('RD_age50','RD_age75','RD_change_75_minus_50')]
for(v in c('estimate','lower95','upper95','bootstrap_mean'))set(key,j=v,value=100*key[[v]])
setnames(key,c('estimate','lower95','upper95','bootstrap_mean'),c('estimate_pp','lower95_pp','upper95_pp','bootstrap_mean_pp'))
fwrite(key,file.path(out,'allcause_key_results_percentage_points.csv'))
